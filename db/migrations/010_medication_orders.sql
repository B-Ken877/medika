-- 010 — Medication orders and manual pharmacy quote operations (issue #83)
--
-- Product rule: a patient can ask Medika to SOURCE the medications of an
-- issued (immutable) prescription. A Medika operations agent contacts a
-- partner pharmacy MANUALLY through WhatsApp, records the pharmacy's
-- confirmed stock and itemized prices, and the patient reviews the quote.
--
-- Separation of concerns (issue #83 hard requirement):
--   * The clinical prescription (prescription_documents, migration 009) is
--     NEVER modified by any of this. Orders reference it read-only; quote
--     entry cannot touch the prescription row. No price exists in the
--     prescription model BY CONSTRUCTION — all prices live here.
--   * Pharmacies are PARTNERS, not users: they never log in. This schema
--     stores only a directory entry (name, WhatsApp contact, location).
--     There are no credentials, no portal, no pharmacy-facing routes.
--
-- Money: every amount is an INTEGER number of Haitian gourdes (HTG) — no
-- decimals anywhere. Quote totals are RECOMPUTED server-side from the
-- itemized lines; client-supplied totals are ignored (same allowlist
-- philosophy as the prescription item fields in migration 009).
--
-- No substitution: quote items map 1:1 to prescription item indices. A
-- clinically meaningful substitution requires prescriber authorization and
-- is intentionally NOT representable here — an item the pharmacy cannot
-- supply is recorded UNAVAILABLE, never silently replaced.
--
-- Privacy: user ids are SET NULL on user deletion (denormalized names
-- survive, mirroring prescription_documents); deleting a consultation
-- cascades its orders (same privacy cleanup as prescription_documents).

-- ─── Partner pharmacy directory (no credentials — WhatsApp only) ────────────
CREATE TABLE IF NOT EXISTS partner_pharmacies (
  id              TEXT PRIMARY KEY,                    -- 'PH_<uuid v4>'
  name            TEXT NOT NULL,
  contact_name    TEXT NOT NULL DEFAULT '',
  -- WhatsApp click-to-chat target, digits with country code (e.g. 509...).
  whatsapp_number TEXT NOT NULL,
  location        TEXT NOT NULL DEFAULT '',
  notes           TEXT NOT NULL DEFAULT '',
  active          BOOLEAN NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ─── Medication orders (patient request to source a prescription) ───────────
--
-- Status machine (all transitions validated SERVER-SIDE under the order row
-- lock — client-supplied status values are never trusted):
--   REQUESTED  -> QUOTED     (ops records a confirmed pharmacy quote)
--   REQUESTED  -> CANCELLED  (patient cancels before any quote)
--   REQUESTED  -> ESCALATED  (30-minute ops SLA target missed — system)
--   ESCALATED  -> QUOTED     (ops eventually records a quote)
--   ESCALATED  -> CANCELLED  (patient gives up pre-quote)
--   QUOTED     -> ACCEPTED   (patient accepts the active, unexpired quote)
--   QUOTED     -> DECLINED   (patient declines the quote)
--   QUOTED     -> EXPIRED    (active quote expiry passed without a decision — system)
--   EXPIRED    -> QUOTED     (ops re-quotes; the previous quote is superseded)
--   ACCEPTED / DECLINED / CANCELLED are terminal for this issue; payment
--   (ACCEPTED -> ...) is the dependent MonCash issue #84.
--
-- SLA: sla_deadline_at = requested_at + 30 minutes, generated by the SERVER
-- from the request timestamp (never from when an agent opens a page). It is
-- an operational target, not a guarantee; ESCALATED is the explicit state
-- when no confirmed quote exists at the deadline.
CREATE TABLE IF NOT EXISTS medication_orders (
  id                       TEXT PRIMARY KEY,                -- 'MO_<uuid v4>'
  -- Human-readable, deterministic reference (same derivation as ORD-…).
  reference                TEXT NOT NULL UNIQUE,
  prescription_document_id TEXT NOT NULL REFERENCES prescription_documents(id),
  consultation_id          TEXT NOT NULL REFERENCES consultations(id) ON DELETE CASCADE,
  patient_id               TEXT REFERENCES users(id) ON DELETE SET NULL,
  patient_name             TEXT NOT NULL DEFAULT '',
  -- Denormalized prescription identity (the order stays readable even if a
  -- consultation cascade is ever bypassed by future privacy tooling).
  prescription_reference   TEXT NOT NULL DEFAULT '',
  status                   TEXT NOT NULL DEFAULT 'REQUESTED' CHECK (status IN
                             ('REQUESTED', 'ESCALATED', 'QUOTED', 'ACCEPTED',
                              'DECLINED', 'CANCELLED', 'EXPIRED')),
  requested_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  sla_deadline_at          TIMESTAMPTZ NOT NULL,
  -- Optional patient-provided delivery context for the manual quote call.
  delivery_address         TEXT NOT NULL DEFAULT '',
  delivery_phone           TEXT NOT NULL DEFAULT '',
  delivery_zone            TEXT NOT NULL DEFAULT '',
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ONE active (non-terminal) order per prescription document, enforced at the
-- DATABASE level so no race or double-click can duplicate a request. After a
-- terminal DECLINED/CANCELLED the patient may start a fresh order.
CREATE UNIQUE INDEX IF NOT EXISTS uq_medication_orders_active
  ON medication_orders (prescription_document_id)
  WHERE status NOT IN ('DECLINED', 'CANCELLED');

CREATE INDEX IF NOT EXISTS idx_medication_orders_patient
  ON medication_orders (patient_id, requested_at DESC)
  WHERE patient_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_medication_orders_status
  ON medication_orders (status, sla_deadline_at);

-- ─── Pharmacy quotes (append-only history; the LATEST is active) ────────────
--
-- Itemized, allowlisted snapshot lines. Each line maps to exactly one
-- prescription item index (availability per prescribed item):
--   availability: AVAILABLE | PARTIAL | UNAVAILABLE
--   AVAILABLE/PARTIAL carry unit_price_htg + quantity (> 0); the subtotal is
--   computed server-side as unit_price_htg * quantity. UNAVAILABLE lines
--   carry NO prices (the pharmacy cannot supply the item — nothing is billed).
CREATE TABLE IF NOT EXISTS pharmacy_quotes (
  id                  TEXT PRIMARY KEY,                  -- 'PQ_<uuid v4>'
  order_id            TEXT NOT NULL REFERENCES medication_orders(id) ON DELETE CASCADE,
  pharmacy_id         TEXT REFERENCES partner_pharmacies(id) ON DELETE SET NULL,
  -- Denormalized pharmacy identity snapshot (audit robustness).
  pharmacy_name       TEXT NOT NULL DEFAULT '',
  pharmacy_whatsapp   TEXT NOT NULL DEFAULT '',
  items               JSONB NOT NULL DEFAULT '[]'::jsonb,
  total_htg           INTEGER NOT NULL CHECK (total_htg >= 0),
  agent_id            TEXT REFERENCES users(id) ON DELETE SET NULL,
  agent_name          TEXT NOT NULL DEFAULT '',
  -- How the pharmacy response was confirmed (default: WhatsApp phone call).
  confirmation_source TEXT NOT NULL DEFAULT 'WHATSAPP',
  confirmed_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- Ops-entered quote validity end; the server validates it is in the future.
  expires_at          TIMESTAMPTZ NOT NULL,
  notes               TEXT NOT NULL DEFAULT '',
  superseded_at       TIMESTAMPTZ                        -- set when a newer quote is recorded
);

CREATE INDEX IF NOT EXISTS idx_pharmacy_quotes_order
  ON pharmacy_quotes (order_id, confirmed_at DESC);

-- ─── Append-only order events / audit history ───────────────────────────────
--
-- Every important transition lands here with actor and timestamp. INSERT
-- only — no code path ever updates or deletes a row (append-only by design).
CREATE TABLE IF NOT EXISTS medication_order_events (
  id          BIGSERIAL PRIMARY KEY,
  order_id    TEXT NOT NULL REFERENCES medication_orders(id) ON DELETE CASCADE,
  event_type  TEXT NOT NULL CHECK (event_type IN
                ('REQUESTED', 'QUOTE_RECORDED', 'QUOTE_REVISED',
                 'PHARMACY_UNREACHABLE', 'ACCEPTED', 'DECLINED',
                 'CANCELLED', 'ESCALATED', 'QUOTE_EXPIRED')),
  actor_id    TEXT,
  actor_name  TEXT NOT NULL DEFAULT '',
  actor_role  TEXT NOT NULL DEFAULT '',                -- 'patient' | 'admin' | 'system'
  details     JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_medication_order_events_order
  ON medication_order_events (order_id, created_at);
